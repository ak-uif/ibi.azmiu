CREATE TABLE programs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(255),
    status VARCHAR(255) NOT NULL,
    title_az VARCHAR(255) NOT NULL,
    title_en VARCHAR(255),
    description_az TEXT NOT NULL,
    description_en TEXT,
    details_az TEXT,
    details_en TEXT,
    duration_az VARCHAR(255),
    duration_en VARCHAR(255),
    audience_az VARCHAR(255),
    audience_en VARCHAR(255),
    deadline_az VARCHAR(255),
    deadline_en VARCHAR(255),
    period_az VARCHAR(255),
    period_en VARCHAR(255),
    icon VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_label VARCHAR(255),
    month_az VARCHAR(255),
    month_en VARCHAR(255),
    title_az VARCHAR(255) NOT NULL,
    title_en VARCHAR(255),
    location_az VARCHAR(255),
    location_en VARCHAR(255),
    time_az VARCHAR(255),
    time_en VARCHAR(255),
    attendees VARCHAR(255),
    speaker_az VARCHAR(255),
    speaker_en VARCHAR(255),
    description_az TEXT NOT NULL,
    description_en TEXT,
    details_az TEXT,
    details_en TEXT,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_az VARCHAR(255),
    category_en VARCHAR(255),
    date_az VARCHAR(255),
    date_en VARCHAR(255),
    title_az VARCHAR(255) NOT NULL,
    title_en VARCHAR(255),
    summary_az TEXT,
    summary_en TEXT,
    full_text_az TEXT,
    full_text_en TEXT,
    image_url VARCHAR(2048),
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE mentors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
