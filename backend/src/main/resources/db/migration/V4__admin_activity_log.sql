CREATE TABLE admin_activity_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_username VARCHAR(255) NOT NULL,
    action VARCHAR(64) NOT NULL,
    record_type VARCHAR(64),
    record_id BIGINT,
    detail VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_admin_activity_created ON admin_activity_log (created_at DESC, id DESC);
CREATE INDEX idx_admin_activity_action ON admin_activity_log (action);
CREATE INDEX idx_admin_activity_actor ON admin_activity_log (admin_username);
CREATE INDEX idx_admin_activity_record ON admin_activity_log (record_type, record_id);
